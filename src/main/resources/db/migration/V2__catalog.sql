-- What's playing where: cities -> cinemas -> screens (with a fixed seat layout) -> shows.
-- Show times are timestamptz: the server runs in UTC, the audience in Asia/Kolkata.

-- Needed for the "no overlapping shows on a screen" exclusion constraint below
create extension if not exists btree_gist;

create table cities (
    id    bigint generated by default as identity primary key,
    name  varchar(60) not null unique,
    state varchar(60) not null
);

create table cinemas (
    id         bigint generated by default as identity primary key,
    city_id    bigint       not null references cities (id),
    name       varchar(120) not null,
    address    varchar(300) not null,
    created_at timestamptz  not null,
    constraint uk_cinema_city_name unique (city_id, name)
);

create table screens (
    id        bigint generated by default as identity primary key,
    cinema_id bigint      not null references cinemas (id),
    name      varchar(40) not null,
    constraint uk_screen_cinema_name unique (cinema_id, name)
);

-- grid_col is the seat's column in the drawn layout, so aisles are gaps in the numbering of columns
create table seats (
    id          bigint generated by default as identity primary key,
    screen_id   bigint      not null references screens (id),
    row_label   varchar(3)  not null,
    seat_number integer     not null check (seat_number > 0),
    grid_col    integer     not null check (grid_col > 0),
    category    varchar(20) not null check (category in ('RECLINER', 'PRIME', 'CLASSIC')),
    constraint uk_seat_position unique (screen_id, row_label, seat_number),
    constraint uk_seat_grid unique (screen_id, row_label, grid_col)
);

create table movies (
    id               bigint generated by default as identity primary key,
    title            varchar(150)  not null,
    synopsis         varchar(2000) not null,
    duration_minutes integer       not null check (duration_minutes between 30 and 300),
    language         varchar(30)   not null,
    certificate      varchar(5)    not null check (certificate in ('U', 'UA', 'A')),
    genres           varchar(200)  not null, -- comma-separated, e.g. "Action,Thriller"
    release_date     date          not null,
    poster_url       varchar(500),
    created_at       timestamptz   not null,
    updated_at       timestamptz
);

create table shows (
    id         bigint generated by default as identity primary key,
    movie_id   bigint      not null references movies (id),
    screen_id  bigint      not null references screens (id),
    starts_at  timestamptz not null,
    ends_at    timestamptz not null, -- start + running time + cleaning buffer
    format     varchar(10) not null check (format in ('2D', '3D', 'IMAX')),
    status     varchar(20) not null check (status in ('SCHEDULED', 'CANCELLED')),
    created_at timestamptz not null,
    constraint ck_show_times check (ends_at > starts_at),
    -- The database itself refuses two scheduled shows on one screen at overlapping times, so two
    -- admins scheduling at once can't double-book a screen (no check-then-insert race in the app).
    constraint ex_show_screen_overlap exclude using gist (
        screen_id with =,
        tstzrange(starts_at, ends_at) with &&
    ) where (status = 'SCHEDULED')
);

create index idx_shows_movie_start on shows (movie_id, starts_at);

-- Ticket price per seat category for a show, in paise (integer money: no floating-point rounding)
create table show_prices (
    id          bigint generated by default as identity primary key,
    show_id     bigint      not null references shows (id) on delete cascade,
    category    varchar(20) not null check (category in ('RECLINER', 'PRIME', 'CLASSIC')),
    price_paise integer     not null check (price_paise > 0),
    constraint uk_show_price unique (show_id, category)
);
