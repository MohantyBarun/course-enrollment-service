-- One row per handled notification, for the admin "Emails" page. The body preview never contains
-- the temporary password (it's masked before the row is written).
create table notification_log (
    id           bigint generated by default as identity primary key,
    message_id   uuid          not null unique,
    event_type   varchar(100)  not null,
    recipient    varchar(150)  not null,
    subject      varchar(200)  not null,
    body_preview varchar(2000) not null,
    delivery     varchar(20)   not null check (delivery in ('SENT', 'SKIPPED')),
    detail       varchar(300),
    created_at   timestamp(6)  not null
);
