-- Baseline: the schema as Hibernate (ddl-auto=update) created it before Flyway was introduced.
-- Existing databases are baselined at version 1 (spring.flyway.baseline-on-migrate), so this
-- script only runs on fresh databases. Constraint names are Hibernate's, to match existing ones.


create table admin (
    id bigint not null,
    admin_level varchar(255) check (admin_level in ('SUPER_ADMIN','ADMIN')),
    department varchar(255),
    primary key (id)
);

create table announcements (
    created_at timestamp(6),
    id bigint generated by default as identity,
    audience_department varchar(100),
    author_name varchar(100),
    title varchar(150) not null,
    body varchar(2000) not null,
    primary key (id)
);

create table attendance_records (
    class_date date not null,
    present boolean not null,
    enrollment_id bigint not null,
    id bigint generated by default as identity,
    primary key (id),
    constraint uk_attendance_enrollment_date unique (enrollment_id, class_date)
);

create table courses (
    capacity integer not null,
    credits integer not null,
    enrollment_open boolean not null,
    created_at timestamp(6),
    id bigint generated by default as identity,
    updated_at timestamp(6),
    code varchar(20) not null unique,
    term varchar(50) not null,
    department varchar(100) not null,
    instructor varchar(100),
    schedule varchar(100),
    title varchar(150) not null,
    description varchar(1000),
    primary key (id)
);

create table enrollments (
    course_id bigint not null,
    enrolled_at timestamp(6),
    id bigint generated by default as identity,
    student_id bigint not null,
    updated_at timestamp(6),
    grade varchar(10) check (grade in ('O','A_PLUS','A','B_PLUS','B','C','P','F')),
    status varchar(20) not null check (status in ('ENROLLED','DROPPED','COMPLETED')),
    primary key (id),
    constraint uk_enrollment_student_course unique (student_id, course_id)
);

create table login_security (
    permanent_block boolean not null,
    wrong_password_count integer not null,
    block_expiry_at timestamp(6),
    blocked_at timestamp(6),
    id bigint not null,
    last_failed_at timestamp(6),
    last_login_at timestamp(6),
    unblocked_at timestamp(6),
    account_status varchar(255) not null check (account_status in ('ACTIVE','BLOCKED','PERMANENTLY_BLOCKED')),
    block_reason varchar(255),
    primary key (id)
);

create table persons (
    id bigint generated by default as identity,
    name varchar(100) not null,
    email varchar(150) not null unique,
    primary key (id)
);

create table refresh_tokens (
    is_revoked boolean not null,
    created_at timestamp(6),
    expiry_date timestamp(6) not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    ip_address varchar(100),
    token varchar(512) not null unique,
    device_info varchar(255),
    primary key (id)
);

create table students (
    date_of_birth date not null,
    created_at timestamp(6),
    id bigint not null,
    updated_at timestamp(6),
    permanent_address varchar(400),
    present_address varchar(400),
    branch varchar(255) not null,
    department varchar(255) not null,
    primary key (id)
);

create table users (
    is_active boolean not null,
    is_email_verified boolean not null,
    is_first_time_login boolean not null,
    temp_password_attempts_count integer not null,
    created_at timestamp(6),
    id bigint not null,
    temp_password_expiry timestamp(6),
    updated_at timestamp(6),
    email varchar(150) not null unique,
    password varchar(255),
    role varchar(255) not null check (role in ('ROLE_STUDENT','ROLE_ADMIN','ROLE_SUPER_ADMIN')),
    temp_password varchar(255),
    primary key (id)
);

