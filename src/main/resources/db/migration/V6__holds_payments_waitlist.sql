-- Phase 2: picking seats holds them for 10 minutes; paying converts the hold into a booking.
-- Seats that come free (expired holds, cancellations) are offered to the waitlist first.

create table seat_holds (
    id                    bigint generated by default as identity primary key,
    show_id               bigint      not null references shows (id),
    user_id               bigint      not null references users (id),
    status                varchar(20) not null check (status in ('ACTIVE', 'CONVERTED', 'EXPIRED', 'RELEASED')),
    source                varchar(20) not null check (source in ('CUSTOMER', 'WAITLIST')),
    seat_count            integer     not null check (seat_count between 1 and 10),
    tickets_paise         integer     not null check (tickets_paise > 0),
    convenience_fee_paise integer     not null check (convenience_fee_paise >= 0),
    expires_at            timestamptz not null,
    created_at            timestamptz not null,
    closed_at             timestamptz,
    booking_id            bigint references bookings (id)
);

-- One live hold per customer per show: choosing seats again replaces it
create unique index uk_one_active_hold on seat_holds (user_id, show_id) where status = 'ACTIVE';
-- The expiry job looks for "ACTIVE and past expires_at"
create index idx_holds_expiring on seat_holds (expires_at) where status = 'ACTIVE';

-- Seats can now be HELD by a hold, as well as AVAILABLE or BOOKED
alter table show_seats drop constraint ck_show_seat_booking;
alter table show_seats drop constraint show_seats_status_check;
alter table show_seats add column hold_id bigint references seat_holds (id);
alter table show_seats add constraint show_seats_status_check
    check (status in ('AVAILABLE', 'HELD', 'BOOKED'));
alter table show_seats add constraint ck_show_seat_owner check (
    (status = 'AVAILABLE' and hold_id is null and booking_id is null) or
    (status = 'HELD' and hold_id is not null and booking_id is null) or
    (status = 'BOOKED' and booking_id is not null and hold_id is null));
create index idx_show_seats_hold on show_seats (hold_id) where hold_id is not null;

-- Our side of a payment. The gateway reference is how webhooks find it.
create table payments (
    id             bigint generated by default as identity primary key,
    hold_id        bigint       not null references seat_holds (id),
    user_id        bigint       not null references users (id),
    gateway_ref    varchar(40)  not null unique,
    amount_paise   integer      not null check (amount_paise > 0),
    status         varchar(20)  not null check (status in ('PENDING', 'SUCCEEDED', 'FAILED', 'REFUNDED')),
    failure_reason varchar(300),
    created_at     timestamptz  not null,
    updated_at     timestamptz  not null
);

-- At most one payment in flight per hold, and at most one that took the money
create unique index uk_payment_pending on payments (hold_id) where status = 'PENDING';
create unique index uk_payment_succeeded on payments (hold_id) where status = 'SUCCEEDED';

alter table bookings add column payment_id bigint references payments (id);

-- Webhooks we have processed, by the gateway's event id: a redelivered event is acknowledged
-- and skipped. Written in the same transaction as the processing, so a failure is retried.
create table payment_webhook_events (
    event_id     varchar(60)  not null primary key,
    event_type   varchar(50)  not null,
    gateway_ref  varchar(40)  not null,
    received_at  timestamptz  not null
);

-- The mock payment gateway's own outbound queue (in a real setup this lives at the provider):
-- it delivers signed webhooks to us over HTTP and retries with backoff until we answer 2xx.
create table mock_gateway_events (
    id              varchar(60)  not null primary key,
    gateway_ref     varchar(40)  not null,
    event_type      varchar(50)  not null,
    payload         text         not null,
    status          varchar(20)  not null check (status in ('PENDING', 'DELIVERED', 'FAILED')),
    attempts        integer      not null default 0,
    next_attempt_at timestamptz  not null,
    last_error      varchar(500),
    created_at      timestamptz  not null,
    delivered_at    timestamptz
);

create index idx_mock_gateway_pending on mock_gateway_events (next_attempt_at) where status = 'PENDING';

-- Customers waiting for a sold-out show. When seats come free, the first entry that fits gets
-- them as a hold (OFFERED) and 10 minutes to pay; if it lapses, the next entry is offered.
create table waitlist_entries (
    id           bigint generated by default as identity primary key,
    show_id      bigint      not null references shows (id),
    user_id      bigint      not null references users (id),
    seats_wanted integer     not null check (seats_wanted between 1 and 6),
    status       varchar(20) not null check (status in ('WAITING', 'OFFERED', 'FULFILLED', 'LAPSED', 'LEFT', 'CLOSED')),
    hold_id      bigint references seat_holds (id),
    created_at   timestamptz not null,
    updated_at   timestamptz not null
);

create unique index uk_waitlist_open on waitlist_entries (show_id, user_id) where status in ('WAITING', 'OFFERED');
create index idx_waitlist_queue on waitlist_entries (show_id, created_at) where status = 'WAITING';
