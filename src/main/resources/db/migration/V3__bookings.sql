create table bookings (
    id                    bigint generated by default as identity primary key,
    reference             varchar(12) not null unique, -- shown on the ticket, e.g. SS7K2M9QXA
    user_id               bigint      not null references users (id),
    show_id               bigint      not null references shows (id),
    status                varchar(20) not null check (status in ('CONFIRMED', 'CANCELLED')),
    seat_count            integer     not null check (seat_count between 1 and 10),
    tickets_paise         integer     not null check (tickets_paise > 0),
    convenience_fee_paise integer     not null check (convenience_fee_paise >= 0),
    created_at            timestamptz not null,
    cancelled_at          timestamptz,
    cancel_reason         varchar(200)
);

create index idx_bookings_user on bookings (user_id, created_at desc);
create index idx_bookings_show on bookings (show_id);

-- What was bought, frozen at booking time (later layout or price changes don't rewrite history)
create table booking_seats (
    id          bigint generated by default as identity primary key,
    booking_id  bigint      not null references bookings (id) on delete cascade,
    seat_id     bigint      not null references seats (id),
    seat_label  varchar(8)  not null, -- e.g. "H12"
    category    varchar(20) not null,
    price_paise integer     not null check (price_paise > 0),
    constraint uk_booking_seat unique (booking_id, seat_id)
);

-- One row per seat per show: the inventory that bookings compete for. Rows are created with the
-- show, so booking is "lock these rows and flip them", never "insert if nobody else did".
create table show_seats (
    id         bigint generated by default as identity primary key,
    show_id    bigint      not null references shows (id) on delete cascade,
    seat_id    bigint      not null references seats (id),
    status     varchar(20) not null check (status in ('AVAILABLE', 'BOOKED')),
    booking_id bigint references bookings (id),
    constraint uk_show_seat unique (show_id, seat_id),
    -- A booked seat always belongs to a booking, and an available one never does
    constraint ck_show_seat_booking check ((status = 'AVAILABLE') = (booking_id is null))
);

create index idx_show_seats_booking on show_seats (booking_id) where booking_id is not null;
