-- Accounts. Customers sign up themselves; admins are seeded (ADMIN_EMAIL / ADMIN_PASSWORD).
create table users (
    id         bigint generated by default as identity primary key,
    name       varchar(100) not null,
    email      varchar(150) not null unique, -- always stored lower-case
    phone      varchar(20),
    password   varchar(255) not null,         -- BCrypt hash
    role       varchar(30)  not null check (role in ('ROLE_CUSTOMER', 'ROLE_ADMIN')),
    is_active  boolean      not null default true,
    created_at timestamp(6) not null,
    updated_at timestamp(6)
);

-- Brute-force protection: 5 wrong passwords block the account for 30 minutes, more than 10 block it for good.
create table login_security (
    id                   bigint       not null primary key references users (id) on delete cascade,
    wrong_password_count integer      not null default 0,
    account_status       varchar(30)  not null check (account_status in ('ACTIVE', 'BLOCKED', 'PERMANENTLY_BLOCKED')),
    permanent_block      boolean      not null default false,
    last_login_at        timestamp(6),
    last_failed_at       timestamp(6),
    blocked_at           timestamp(6),
    unblocked_at         timestamp(6),
    block_expiry_at      timestamp(6),
    block_reason         varchar(255)
);

-- Refresh tokens are opaque random strings; only their SHA-256 hash is stored, so a database leak
-- doesn't leak usable sessions. Each use rotates the token inside its family; presenting a token
-- that was already rotated means it was stolen (or replayed), and the whole family is revoked.
create table refresh_tokens (
    id          bigint generated by default as identity primary key,
    user_id     bigint       not null references users (id) on delete cascade,
    token_hash  varchar(64)  not null unique,
    family_id   uuid         not null,
    expires_at  timestamp(6) not null,
    revoked_at  timestamp(6),
    created_at  timestamp(6) not null
);

create index idx_refresh_tokens_user on refresh_tokens (user_id);
create index idx_refresh_tokens_family on refresh_tokens (family_id);
